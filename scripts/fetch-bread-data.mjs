/**
 * Bread and Butter: fetch the real prices and pay from FRED (the St. Louis Fed's republication of BLS data) and
 * write src/bread/engine/data.ts. Run it again to bring the demo up to date: `node scripts/fetch-bread-data.mjs`.
 *
 * Prices: BLS Average Price Data, U.S. city average, monthly, not seasonally adjusted (dollars per unit).
 * Pay: BLS Current Population Survey, median usual weekly earnings, full-time wage and salary workers, nominal
 * dollars, quarterly, seasonally adjusted. Before tax.
 *
 * Missing months (the BLS did not publish a price) are written as null; the engine fills them by straight-line
 * interpolation between the nearest known months and says so on the page.
 */
import { writeFileSync } from 'node:fs';

const START = '1980-01';
const ITEMS = [
  { key: 'bread', series: 'APU0000702111', name: 'Bread, white, pan (per lb)' },
  { key: 'eggs', series: 'APU0000708111', name: 'Eggs, grade A, large (per dozen)' },
  { key: 'coffee', series: 'APU0000717311', name: 'Coffee, 100%, ground roast (per lb)' },
  { key: 'bananas', series: 'APU0000711211', name: 'Bananas (per lb)' },
  { key: 'chicken', series: 'APU0000706111', name: 'Chicken, fresh, whole (per lb)' },
  { key: 'flour', series: 'APU0000701111', name: 'Flour, white, all purpose (per lb)' },
];
const PAY = { series: 'LES1252881500Q', name: 'Median usual weekly earnings, full-time wage and salary workers (nominal)' };
// all prices, for the notes' inflation rate (12-month change); starts 1913, so January 1979 is there for 1980's rate
const CPI = { series: 'CPIAUCNS', name: 'Consumer Price Index, all urban consumers, all items, not seasonally adjusted' };

async function fredCsv(id) {
  const res = await fetch(`https://fred.stlouisfed.org/graph/fredgraph.csv?id=${id}`);
  if (!res.ok) throw new Error(`${id}: HTTP ${res.status}`);
  const rows = (await res.text()).trim().split(/\r?\n/).slice(1);
  return rows.map((r) => {
    const [date, v] = r.split(',');
    return { month: date.slice(0, 7), value: v === '' || v === '.' ? null : Number(v) };
  });
}

const monthIndex = (ym) => {
  const [y, m] = ym.split('-').map(Number);
  return (y - 1980) * 12 + (m - 1);
};

const prices = {};
const gaps = {};
let lastMonth = Infinity;
for (const item of ITEMS) {
  const rows = (await fredCsv(item.series)).filter((r) => r.month >= START);
  const known = rows.filter((r) => r.value !== null);
  lastMonth = Math.min(lastMonth, monthIndex(known[known.length - 1].month));
  prices[item.key] = rows;
}
const payAll = (await fredCsv(PAY.series)).filter((r) => r.month >= START);
const payRows = payAll.filter((r) => r.value !== null);
// a quarter's pay covers its three months: the data runs to the end of the last published quarter
const payEnd = monthIndex(payRows[payRows.length - 1].month) + 2;
lastMonth = Math.min(lastMonth, payEnd);
const months = lastMonth + 1;

const cpiRows = (await fredCsv(CPI.series)).filter((r) => r.month >= '1979-01' && r.value !== null);
const cpi = new Array(months + 12).fill(null); // index 0 = 1979-01, so cpi[m + 12] is month m
for (const r of cpiRows) {
  const i = monthIndex(r.month) + 12;
  if (i >= 0 && i < cpi.length) cpi[i] = r.value;
}
if (cpi[0] === null || cpi[cpi.length - 1] === null) throw new Error('cpi: no figure for the first or last month');
const cpiGaps = cpi.flatMap((v, i) => (v === null ? [i - 12] : []));

const series = {};
for (const item of ITEMS) {
  const arr = new Array(months).fill(null);
  for (const r of prices[item.key]) {
    const i = monthIndex(r.month);
    if (i >= 0 && i < months) arr[i] = r.value;
  }
  series[item.key] = arr;
  gaps[item.key] = arr.flatMap((v, i) => (v === null ? [i] : []));
  if (arr[0] === null || arr[months - 1] === null) throw new Error(`${item.key}: no price at the first or last month`);
}
const pay = new Array(Math.ceil(months / 3)).fill(null);
for (const r of payRows) {
  const q = Math.floor(monthIndex(r.month) / 3);
  if (q >= 0 && q < pay.length) pay[q] = r.value;
}
if (pay[0] === null || pay[pay.length - 1] === null) throw new Error('pay: no figure for the first or last quarter');
const payGaps = pay.flatMap((v, q) => (v === null ? [q] : []));

const ym = (i) => `${1980 + Math.floor(i / 12)}-${String((i % 12) + 1).padStart(2, '0')}`;
const fmt = (a) => `[${a.map((v) => (v === null ? 'null' : String(v))).join(',')}]`;
const out = `/**
 * Bread and Butter: real prices and pay, generated by scripts/fetch-bread-data.mjs on ${new Date().toISOString().slice(0, 10)}.
 * Do not edit by hand; run the script again to update.
 *
 * Sources (FRED, Federal Reserve Bank of St. Louis, from the U.S. Bureau of Labor Statistics):
${ITEMS.map((i) => ` *   ${i.key}: ${i.series}, ${i.name}`).join('\n')}
 *   pay: ${PAY.series}, ${PAY.name}
 *   cpi: ${CPI.series}, ${CPI.name}
 *
 * Months run from ${START} (index 0) to ${ym(months - 1)} (index ${months - 1}). null = no published price that month
 * (filled by interpolation in the engine). Pay is per quarter (index q covers months 3q to 3q + 2).
 */

export const DATA_START = '${START}';
export const DATA_MONTHS = ${months};
export const DATA_FETCHED = '${new Date().toISOString().slice(0, 10)}';

export const PRICE_SERIES = {
${ITEMS.map((i) => `  ${i.key}: '${i.series}',`).join('\n')}
} as const;
export const PAY_SERIES = '${PAY.series}';
export const CPI_SERIES = '${CPI.series}';

export const PRICES: Record<keyof typeof PRICE_SERIES, readonly (number | null)[]> = {
${ITEMS.map((i) => `  ${i.key}: ${fmt(series[i.key])},`).join('\n')}
};

/** Median usual weekly pay (dollars, before tax), per quarter; null = not published (filled by interpolation). */
export const WEEKLY_PAY: readonly (number | null)[] = ${fmt(pay)};

/** All-items consumer price index (1982-84 = 100), monthly from 1979-01: CPI[m + 12] is month m (12 months earlier
 *  is CPI[m]), so the 12-month inflation rate at month m is CPI[m + 12] / CPI[m] - 1. null = not published. */
export const CPI: readonly (number | null)[] = ${fmt(cpi)};
`;
writeFileSync(new URL('../src/bread/engine/data.ts', import.meta.url), out);
console.log(`months ${months} (${START} to ${ym(months - 1)}), quarters ${pay.length}`);
const yq = (q) => `${1980 + Math.floor(q / 4)} Q${(q % 4) + 1}`;
if (cpiGaps.length) console.log(`  gaps in cpi: ${cpiGaps.map(ym).join(', ')}`);
if (payGaps.length) console.log(`  gaps in pay: ${payGaps.map(yq).join(', ')}`);
for (const [k, g] of Object.entries(gaps)) if (g.length) console.log(`  gaps in ${k}: ${g.length} months (${ym(g[0])} to ${ym(g[g.length - 1])})`);
