import { createRequire } from 'node:module';
const PW = process.env.PLAYWRIGHT_PATH ?? 'playwright';
const { chromium } = createRequire(import.meta.url)(PW);
const browser = await chromium.launch({ args: process.env.GPU ? ['--use-angle=d3d11','--ignore-gpu-blocklist','--enable-gpu-rasterization','--enable-zero-copy','--disable-software-rasterizer'] : [] });
const page = await browser.newPage({ viewport: { width: 1280, height: 1500 }, deviceScaleFactor: 2 });
await page.goto('http://localhost:5174/slice.html');
await page.waitForSelector('body[data-ready="1"]', { timeout: 120000 });
const r = await page.evaluate(() => {
  const big = window.__slice.big;
  const tp = big.painter;
  const ctx = big.canvas.getContext('2d');
  const N = 100;
  const time = (fn) => { const t = performance.now(); for (let i = 0; i < N; i++) fn(i); ctx.getImageData(0,0,1,1); return (performance.now() - t) / N; };
  const view = { ox: big.cssW / 2, oy: big.oy, s: big.s };
  const out = {};
  out.paper = time(() => ctx.drawImage(big.backdrop.paper, 0, 0, big.cssW, big.cssH));
  out.ground = time(() => ctx.drawImage(big.backdrop.ground, 0, big.oy - 30, big.cssW, big.backdrop.groundH));
  out.paint = time((i) => tp.paint(ctx, view, { maturity: 1, months: 12, timeMs: i * 16, wind: true }, big.sprites));
  out.paintNoWind = time((i) => tp.paint(ctx, view, { maturity: 1, months: 12, timeMs: 0, wind: false }, big.sprites));
  const ord = tp.model.order; tp.model.order = new Int32Array(0);
  out.skeletonOnly = time((i) => tp.paint(ctx, view, { maturity: 1, months: 12, timeMs: 0, wind: false }, big.sprites));
  tp.model.order = ord;
  const sp = big.sprites.kinds.front[0];
  out.draw126 = time(() => { for (let k = 0; k < 126; k++) ctx.drawImage(sp, 100 + k, 100 + k, 110, 70); });
  out.draw126a = time(() => { ctx.globalAlpha = 0.8; for (let k = 0; k < 126; k++) ctx.drawImage(sp, 100 + k, 100 + k, 110, 70); ctx.globalAlpha = 1; });
  out.sprite = [sp.width, sp.height];
  out.dpr = window.devicePixelRatio; out.canvas = [big.canvas.width, big.canvas.height];
  out.gl = (() => { const c = document.createElement('canvas'); const g = c.getContext('webgl'); const e = g && g.getExtension('WEBGL_debug_renderer_info'); return e ? g.getParameter(e.UNMASKED_RENDERER_WEBGL) : 'none'; })();
  return out;
});
console.log(r);
await browser.close();
